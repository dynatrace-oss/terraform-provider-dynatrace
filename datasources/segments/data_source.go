func DataSource() *schema.Resource {
	scm := hcl.SetComputedSchema(new(segmentsettings.Segment).Schema())
	scm["name"] = &schema.Schema{
		Type:         schema.TypeString,
		Description:  "Name of the segment. Exactly one of `name` or `id` must be set",
		Optional:     true,
		Computed:     true,
		ExactlyOneOf: []string{"name", "id"},
	}
	scm["id"] = &schema.Schema{
		Type:         schema.TypeString,
		Description:  "ID (uid) of the segment, generated by Dynatrace on creation. Exactly one of `name` or `id` must be set",
		Optional:     true,
		Computed:     true,
		ExactlyOneOf: []string{"name", "id"},
	}

	scm["include_ready_made"] = &schema.Schema{
		Type:        schema.TypeBool,
		Description: "If `true`, ready-made segments are also found when looking up by `name`. Defaults to `false`",
		Optional:    true,
	}

	return &schema.Resource{
		ReadContext: logging.EnableDSCtx(DataSourceRead),
		Schema:      scm,
	}
}

func DataSourceRead(ctx context.Context, d *schema.ResourceData, m any) diag.Diagnostics {
	clientSet, err := config.ClientSet(m, config.CredValDefault)
	if err != nil {
		return diag.FromErr(err)
	}

	service, err := segmentservice.Service(clientSet)
	if err != nil {
		return diag.FromErr(err)
	}

	id := d.Get("id").(string)
	if id == "" {
		platformClient, err := clientSet.PlatformClient()
		if err != nil {
			return diag.FromErr(err)
		}

		listResponse, err := segmentsclient.NewClient(platformClient).List(ctx)
		if err != nil {
			return diag.FromErr(err)
		}

		var stubs []segmentservice.SegmentStub
		if err = json.Unmarshal(listResponse.Data, &stubs); err != nil {
			return diag.FromErr(err)
		}

		id = findIDByName(stubs, d.Get("name").(string), d.Get("include_ready_made").(bool))
		if id == "" {
			d.SetId("")
			return diag.Diagnostics{}
		}
	}

	var v segmentsettings.Segment
	if err = service.Get(ctx, id, &v); err != nil {
		return diag.FromErr(err)
	}

	marshalled := hcl.Properties{}
	if err = v.MarshalHCL(marshalled); err != nil {
		return diag.FromErr(err)
	}

	for k, val := range marshalled {
		if err = d.Set(k, val); err != nil {
			return diag.FromErr(err)
		}
	}

	d.SetId(id)
	return diag.Diagnostics{}
}

func findIDByName(stubs []segmentservice.SegmentStub, name string, includeReadyMade bool) string {
	for _, stub := range stubs {
		if stub.IsReadyMade && !includeReadyMade {
			continue
		}
		if stub.Name == name {
			return stub.UID
		}
	}
	return ""
}
